# 재료 입력 칸
입력재료 = st.text_input(
    "냉장고에 있는 재료를 입력하세요",
    placeholder="예: 계란, 양파, 대파, 햄"
)

# 요리 추천 버튼
if st.button("요리 추천받기"):

    if not 입력재료.strip():
        st.warning("재료를 먼저 입력해주세요.")

    else:
        # 쉼표를 기준으로 재료 나누기
        재료입력값 = 입력재료.replace(" ", "")
        입력한재료 = [
            재료 for 재료 in 재료입력값.split(",")
            if 재료
        ]

        # 요리별 점수 계산
        추천결과 = []

        for 요리 in 요리목록:

            겹치는재료 = []

            for 재료 in 입력한재료:
                for 요리재료 in 요리["재료"]:
                    if 재료 in 요리재료 or 요리재료 in 재료:
                        if 요리재료 not in 겹치는재료:
                            겹치는재료.append(요리재료)

            점수 = len(겹치는재료)

            if 점수 > 0:
                추천결과.append({
                    "이름": 요리["이름"],
                    "점수": 점수,
                    "겹치는재료": 겹치는재료,
                    "필요한재료": 요리["재료"]
                })

        # 점수가 높은 순서로 정렬
        추천결과.sort(
            key=lambda x: x["점수"],
            reverse=True
        )

        # 추천 결과 표시
        if 추천결과:

            st.subheader("추천 결과")

            # 최대 3개 요리 표시
            for 순서, 결과 in enumerate(추천결과[:3], start=1):

                st.write(f"### {순서}. {결과['이름']}")

                st.write(
                    "가지고 있는 재료: "
                    + ", ".join(결과["겹치는재료"])
                )

                부족한재료 = [
                    재료
                    for 재료 in 결과["필요한재료"]
                    if 재료 not in 결과["겹치는재료"]
                ]

                if 부족한재료:
                    st.write(
                        "추가로 필요한 재료: "
                        + ", ".join(부족한재료)
                    )
                else:
                    st.success("가지고 있는 재료만으로 만들 수 있어요!")

                st.divider()

        else:
            st.info(
                "입력한 재료로 추천할 수 있는 요리를 찾지 못했어요."
            )
